let current = LANGUAGES[0];

function fill(text, vars) {
  return text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined ? `{${k}}` : vars[k]));
}

// t("key", {vars}); keys ending in a plural form are picked with t.plural.
export function t(key, vars = {}) {
  const text = STRINGS[current.id][key] ?? STRINGS.en[key] ?? key;
  const formatted = Object.fromEntries(
    Object.entries(vars).map(([k, v]) => [k, typeof v === "number" ? num(v) : v]),
  );
  return fill(text, formatted);
}

t.plural = (key, n, vars = {}) => {
  const rule = new Intl.PluralRules(current.intl).select(n);
  const table = STRINGS[current.id];
  const found = [`${key}.${rule}`, `${key}.other`].find((k) => k in table || k in STRINGS.en);
  return t(found, { n, ...vars });
};

// Planner notes ({ code, params }) in the current language; see formatParam in planner/plan.js.
export function tNote({ code, params = {} }) {
  const text = STRINGS[current.id][`note.${code}`] ?? STRINGS.en[`note.${code}`] ?? code;
  const fmt = {
    money: (v) => new Intl.NumberFormat(current.intl, { style: "currency", currency: "USD", maximumFractionDigits: 0 }).format(v),
    percent: (v) => pct(v),
    nested: (c) => STRINGS[current.id][`note.${c}`] ?? STRINGS.en[`note.${c}`] ?? c,
  };
  return fill(
    text,
    Object.fromEntries(Object.entries(params).map(([k, v]) => [k, typeof v === "number" && !k.endsWith("_usd") && k !== "pct" ? num(v) : formatParam(k, v, fmt)])),
  );
}

export const lang = () => current;
export const num = (v, opts) => new Intl.NumberFormat(current.intl, opts).format(v);
export const pct = (v, digits = 1) => num(v / 100, { style: "percent", minimumFractionDigits: digits, maximumFractionDigits: digits });
export const date = (value, opts = { day: "numeric", month: "short" }) =>
  value ? new Date(value).toLocaleDateString(current.intl, opts) : t("na");
export const time = (value) => new Date(value).toLocaleTimeString(current.intl, { hour: "2-digit", minute: "2-digit" });

const STORAGE_KEY = "smartfreight.lang";

function initial() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (LANGUAGES.some((l) => l.id === saved)) return saved;
  } catch {
    // Storage can be unavailable (private windows, sandboxed previews).
  }
  const nav = (navigator.language || "en").slice(0, 2);
  return LANGUAGES.some((l) => l.id === nav) ? nav : "en";
}

const LangContext = createContext({ lang: "en", setLang: () => {} });

export function LanguageProvider({ children }) {
  const [id, setId] = useState(initial);
  // Set synchronously so every render below this point formats in the chosen language.
  current = LANGUAGES.find((l) => l.id === id);

  useEffect(() => {
    document.documentElement.lang = id;
    document.documentElement.dir = current.dir;
    try {
      localStorage.setItem(STORAGE_KEY, id);
    } catch {
      // Not persisted; the choice still applies for this visit.
    }
  }, [id]);

  const value = useMemo(() => ({ lang: id, setLang: setId }), [id]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);
